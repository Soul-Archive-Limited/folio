#!/usr/bin/env python3
"""Folio's mark (Batch K: "Nib book" — an open diary whose gutter is a fountain-pen nib).

One source for every place the mark appears. Writes the SVGs, then rasterises the PNGs with
scripts/brand/render-svg.swift (macOS draws SVG natively).

    python3 scripts/brand/generate.py

Outputs: shared/brand/*.svg, the Icon Composer layer (ios/Folio/AppIcon.icon/Assets/mark.svg),
AppMark.imageset (launch, greeting, lock, privacy cover), web favicon + install icons +
apple-touch-icon, and web/src/components/brand-mark.ts (the paths for Mark.astro / Icons.tsx).
"""
import json
import pathlib
import re
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
TOKENS = json.loads((ROOT / "shared/design-tokens.json").read_text())
PAPER = "#FFFDF9"
TILE_TOP, TILE_BOTTOM = "#4150E0", "#252FA6"  # Ink, lit from above (accent #3441D5 sits between)

# Geometry on a 100-unit square. The pages' inner edges follow the nib, 4.5 units away.
LEFT = "M10 30.5 C21 26.5 30 26 37 28.6 L37 41 C34.5 44.5 33 48 33.2 50.5 C33.3 52.5 33.6 53.6 34 54.6 L45.8 84.6 C36 79 22 77 10 79.5 Z"
NIB = "M0 0 L-12 -30 C-13 -35 -12 -40 -9 -44 L-9 -53 Q-9 -58 -4 -58 L4 -58 Q9 -58 9 -53 L9 -44 C12 -40 13 -35 12 -30 Z"
SLIT = " M-1.15 -4 L1.15 -4 L1.15 -26.4 L-1.15 -26.4 Z M-3.6 -30 A3.6 3.6 0 1 0 3.6 -30 A3.6 3.6 0 1 0 -3.6 -30 Z"
# 16-32 px: no slit or breather hole, a wider gutter.
LEFT_SMALL = "M8 30.5 C20 26.5 29 26 35.5 28.6 L35.5 41 C32.5 45 31.5 50 32.5 55 L44 85 C35 79.5 21 77.5 8 80 Z"


def mirror(d: str) -> str:
    """Reflects a path across x = 50 (absolute commands only; arcs aren't used in the pages)."""
    out, is_x = [], True
    for tok in re.findall(r"[A-Za-z]|-?\d*\.?\d+", d):
        if tok.isalpha():
            out.append(tok)
            is_x = True
            continue
        v = float(tok)
        out.append(f"{100 - v:g}" if is_x else f"{v:g}")
        is_x = not is_x
    return " ".join(out)


def mark(small=False, fill=PAPER) -> str:
    left = LEFT_SMALL if small else LEFT
    nib = NIB if small else NIB + SLIT
    scale = 0.9 if small else 0.95
    return (f'<path d="{left}" fill="{fill}"/><path d="{mirror(left)}" fill="{fill}"/>'
            f'<path transform="translate(50 83) scale({scale})" d="{nib}" fill="{fill}" fill-rule="evenodd"/>')


def tile(small=False, radius=22.5) -> str:
    return (f'<defs><linearGradient id="folio-ink" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{TILE_TOP}"/>'
            f'<stop offset="1" stop-color="{TILE_BOTTOM}"/></linearGradient></defs>'
            f'<rect width="100" height="100" rx="{radius}" fill="url(#folio-ink)"/>{mark(small)}')


def svg(body: str, view=100) -> str:
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {view} {view}">{body}</svg>\n'


def write(rel: str, text: str):
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main():
    write("shared/brand/folio-mark.svg", svg(mark()))
    write("shared/brand/folio-mark-small.svg", svg(mark(small=True)))
    write("shared/brand/folio-tile.svg", svg(tile()))
    write("shared/brand/folio-tile-small.svg", svg(tile(small=True)))
    write("shared/brand/folio-mark-ink.svg", svg(mark(fill=TOKENS["colors"]["accent"]["light"])))
    # Icon Composer layer: the mark alone on the 1024-point canvas; the fill lives in icon.json.
    write("ios/Folio/AppIcon.icon/Assets/mark.svg", svg(f'<g transform="scale(10.24)">{mark()}</g>', 1024))
    write("web/public/favicon.svg", svg(tile(small=True)))
    # Paths for the web components (Mark.astro, Icons.tsx), so they never drift from this file.
    write("web/src/components/brand-mark.ts",
          "// Generated by scripts/brand/generate.py — Folio's mark (Batch K). Do not edit.\n"
          f"export const MARK_PATHS = {json.dumps([LEFT, mirror(LEFT)])};\n"
          f"export const NIB_PATH = {json.dumps(NIB + SLIT)};\n"
          "export const NIB_TRANSFORM = 'translate(50 83) scale(0.95)';\n"
          f"export const TILE = {json.dumps({'top': TILE_TOP, 'bottom': TILE_BOTTOM, 'paper': PAPER})};\n")

    render = ROOT / "scripts/brand/render-svg.swift"
    with tempfile.TemporaryDirectory() as tmp:
        tool = pathlib.Path(tmp) / "render"
        subprocess.run(["swiftc", "-O", str(render), "-o", str(tool)], check=True)
        full_bleed = pathlib.Path(tmp) / "full.svg"
        full_bleed.write_text(svg(tile(radius=0)))
        maskable = pathlib.Path(tmp) / "maskable.svg"
        maskable.write_text(svg(f'<rect width="100" height="100" fill="{TILE_BOTTOM}"/>'
                                f'<g transform="translate(14 14) scale(0.72)">{tile(radius=0)}</g>'))

        def png(source, rel, size):
            (ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
            subprocess.run([str(tool), str(source), str(ROOT / rel), str(size)], check=True)

        tile_svg = ROOT / "shared/brand/folio-tile.svg"
        app_mark = "ios/Folio/Resources/Assets.xcassets/AppMark.imageset"
        for scale in (1, 2, 3):
            png(tile_svg, f"{app_mark}/AppMark@{scale}x.png", 72 * scale)
        write(f"{app_mark}/Contents.json", json.dumps({"images": [
            {"filename": f"AppMark@{s}x.png", "idiom": "universal", "scale": f"{s}x"} for s in (1, 2, 3)],
            "info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
        png(tile_svg, "web/public/icons/icon-192.png", 192)
        png(tile_svg, "web/public/icons/icon-512.png", 512)
        png(maskable, "web/public/icons/icon-maskable-512.png", 512)
        png(full_bleed, "web/public/apple-touch-icon.png", 180)
        png(full_bleed, "docs/brand/folio-icon-1024.png", 1024)
    print("Brand assets written.")


if __name__ == "__main__":
    main()
