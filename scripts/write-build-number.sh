#!/bin/sh
# Writes ios/Config/BuildNumber.xcconfig (git-ignored) before every `xcodegen generate`
# (XcodeGen preGenCommand). Build number = CI_BUILD_NUMBER on Xcode Cloud, else the git
# commit count, else 1. Marketing version stays in ios/project.yml.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
config="$here/../ios/Config/BuildNumber.xcconfig"
if [ -n "${CI_BUILD_NUMBER:-}" ]; then
  number="$CI_BUILD_NUMBER"
else
  number=$(git -C "$here/.." rev-list --count HEAD 2>/dev/null || echo 1)
fi
case "$number" in
  ''|*[!0-9]*) echo "write-build-number: '$number' is not an integer" >&2; exit 1 ;;
esac
mkdir -p "$(dirname "$config")"
printf '// Generated by scripts/write-build-number.sh. Do not edit or commit.\nCURRENT_PROJECT_VERSION = %s\n' "$number" > "$config"
echo "Build number: $number"
