// Generates src/styles/tokens.css from shared/design-tokens.json (SPEC §3.2, §11.1), so the
// website and the iPhone app share one colour source. Runs before dev and build.
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../../shared/design-tokens.json', import.meta.url), 'utf8'));

function rgba(hex, alpha) {
  if (alpha === undefined || alpha === 1) return hex.toLowerCase();
  const n = parseInt(hex.slice(1), 16);
  return `rgb(${n >> 16} ${(n >> 8) & 255} ${n & 255} / ${alpha})`;
}

function block(mode) {
  const lines = [];
  for (const [name, t] of Object.entries(tokens.colors)) {
    const alpha = t.alpha?.[mode];
    lines.push(`  --${kebab(name)}: ${rgba(t[mode], alpha)};`);
  }
  for (const [name, t] of Object.entries(tokens.categories)) {
    lines.push(`  --cat-${name}: ${t[mode].toLowerCase()};`);
  }
  return lines.join('\n');
}

function kebab(s) {
  return s.replace(/[A-Z0-9]+/g, (m) => `-${m.toLowerCase()}`).replace(/-(\d)/g, '$1');
}

const css = `/* Generated by scripts/tokens.mjs from shared/design-tokens.json. Do not edit. */
:root {
  color-scheme: light dark;
${block('light')}
}

@media (prefers-color-scheme: dark) {
  :root {
${block('dark').replace(/^ {2}/gm, '    ')}
  }
}
`;

writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), css);
